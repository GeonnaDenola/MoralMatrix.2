        <header class="section-header">
          <span class="section-eyebrow">Section I</span>
          <h2 id="policies-heading">Policies on Student Conduct</h2>
          <p>It is axiomatic that a school should maintain good discipline inside the campus
             as well as outside the school premises when students are engaged in school-sanctioned
             activities. The College recognizes the necessity of spelling out the procedures
             providing for remedies in case of infractions committed by any student against the
             institution, the employees, or co-students.</p>
        </header>

        <div class="section-body">
          <article class="content-card" id="wearing-id" aria-labelledby="wearing-id-heading">
            <h3 id="wearing-id-heading">A. On Wearing of ID, School Uniform and Personal Attire</h3>
            <ul>
              <li>All students are required to wear their IDs with the official ID lace inside the school campus…</li>
              <li>All students are required to be in prescribed uniform except on Wednesdays and Saturdays (wash days)…
                <ul>
                  <li><strong>Men:</strong> Shorts, muscle shirts, tattered denims, and slippers are not allowed.</li>
                  <li><strong>Women:</strong> Shorts, sleeveless or hanging blouses, sleeveless dresses, tops with low or plunging neckline, miniskirts, tattered denims, and slippers are not allowed.</li>
                </ul>
              </li>
              <li>Wearing of slippers will only be allowed during floods and other major weather disturbances.</li>
              <li>The prescribed hairstyle for male students is short (exposing the nape)…</li>
              <li>Students not in proper uniform will not be allowed to attend their classes and shall be marked absent.</li>
              <li>Students are not allowed to attend their academic classes in PE or NSTP uniform.</li>
              <li>All students must refrain from having body piercings and excessive use of accessories…</li>
            </ul>
          </article>

          <article class="content-card" id="use-of-facilities" aria-labelledby="use-of-facilities-heading">
            <h3 id="use-of-facilities-heading">B. On the Use of School Facilities</h3>
            <ul>
              <li>Observe library and computer science laboratory rules and regulations.</li>
              <li>Conserve water and energy whenever possible.</li>
              <li>Exert utmost care and concern in handling laboratory equipment.</li>
              <li>Keep the comfort rooms clean.</li>
              <li>Help keep the campus clean and orderly. Refrain from acts of vandalism.</li>
            </ul>
          </article>
        </div>
      </section>

      <section id="standards" class="handbook-section" aria-labelledby="standards-heading">
        <header class="section-header">
          <h2 id="standards-heading">Standards of Conduct</h2>
          <p>All students are expected to conduct themselves in a manner befitting a student of the College,
             and not to violate any of the rules and regulations of the College.</p>
        </header>

        <article class="content-card" id="classification" aria-labelledby="classification-heading">
          <h3 id="classification-heading">A. Classification of Violations/Offenses</h3>

          <div class="offense-grid">
            <div class="offense-card" id="light-offenses">
              <h4>Light Offenses</h4>
              <p>Light offenses are punished by fine or warning…</p>
              <ul>
                <li>Violation of the Policy on ID, school uniform and attire</li>
                <li>Violation of the Policy on the use of school facilities</li>
                <li>Loitering along the hallway during class hours</li>
              </ul>
            </div>

            <div class="offense-card" id="less-grave-offenses">
              <h4>Less Grave Offenses (Moderate)</h4>
              <p>Offenses which are not very serious in nature…</p>
              <ul>
                <li>Use of curses and vulgar words…</li>
                <li>Use of cellular phones and other gadgets during classes…</li>
                <li>Posting of materials without prior permission…</li>
                <li>Public display of intimacy while in uniform.</li>
                <li>Deliberate cutting of classes…</li>
              </ul>
            </div>

            <div class="offense-card" id="grave-offenses">
              <h4>Grave Offenses</h4>
              <p>For a persistent offender or one guilty of a serious offense…</p>
              <ul>
                <li>Smoking, gambling, or drinking while in school uniform…</li>
                <li>Vandalism, theft, and willful destruction of property</li>
                <li>Hooliganism and brawls on campus</li>
                <li>…and other offenses</li>
              </ul>
            </div>
          </div>
        </article>

        <article class="content-card" id="procedure" aria-labelledby="procedure-heading">
          <h3 id="procedure-heading">B. Procedure of Processing of Student Discipline Cases</h3>

          <div class="process-grid">
            <div class="process-card" id="csd-composition">
              <h4>Committee on Student Discipline (CSD) – Composition</h4>
              <ul>
                <li>Discipline Services Coordinator (Chair)</li>
                <li>Representative from the School Administration</li>
                <li>Representative from the Institute Student Council</li>
                <li>Representative from the Mabalacat College Student Council</li>
                <li>Representative from the Faculty</li>
              </ul>
            </div>

            <div class="process-card" id="jurisdiction">
              <h4>C. Jurisdiction of the CSD</h4>
              <ul>
                <li>Violation of the policies in the Student Manual</li>
                <li>Violation of a School Memorandum</li>
                <li>Crimes involving moral turpitude</li>
                <li>Other unlawful acts</li>
              </ul>
            </div>

            <div class="process-card" id="filing">
              <h4>D. Filing of a Complaint and Reply Thereof</h4>
              <ol>
                <li>A complaint should be in writing, dated, and signed…</li>
                <li>It should state names, acts complained of, damages, remedy sought…</li>
                <li>The Coordinator evaluates sufficiency and grounds…</li>
                <li>If sufficient, CSD convenes and orders a reply within 48 hours…</li>
                <li>Further comments/replies each within forty-eight (48) hours…</li>
              </ol>
            </div>

            <div class="process-card" id="hearing">
              <h4>E. Hearing</h4>
              <ol>
                <li>CSD notifies parties of hearing date/time…</li>
                <li>Complainant presents evidence; can be examined by CSD/erring student…</li>
                <li>Erring student presents defense…</li>
                <li>Unjustified absence does not postpone the hearing…</li>
              </ol>
            </div>

            <div class="process-card" id="decision">
              <h4>F. Decision and Range of Penalties/Sanctions</h4>
              <ul>
                <li>If “guilty” plea, penalty is one step lower.</li>
                <li>CSD releases decision within 15 days from last hearing.</li>
                <li>Appeal path: VPSAS → College President (final and executory).</li>
                <li>Non-appealed decisions become executory.</li>
              </ul>
              <p class="meta-note">Sanctions include: verbal reprimand, written undertaking, community service,
                 public apology, suspension, exclusion, and expulsion.</p>
            </div>
          </div>

          <p class="meta-note">Source text reproduced for clarity. For canonical wording, refer to the official Student Manual.</p>
        </article>
