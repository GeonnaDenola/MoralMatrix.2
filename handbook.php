        <h2 id="policies-heading">I. Policies on Student Conduct</h2>
        <p>It is axiomatic that a school should maintain good school discipline inside the campus as well as outside the school premises when students are engaged in school-sanctioned activities. The College recognizes the necessity of spelling out the procedures providing for remedies in case of infractions committed by any student against the institution, the employees, or co-students.</p>
        <p>All students in this College are expected to conduct themselves properly and strictly observe the following policies:</p>

        <h3 id="wearing-id">A. On Wearing of ID, School Uniform and Personal Attire</h3>
        <ul>
          <li>All students are required to wear their IDs with the official ID lace inside the school campus, whether or not they have classes. Lost IDs must be reported immediately to the Office of Discipline Services (ODS) to obtain an ID pass or permit.</li>
          <li>All students are required to be in prescribed uniform except on Wednesdays and Saturdays (wash days). Modesty and decency should be observed when wearing civilian attire.
            <ul>
              <li><strong>Men:</strong> Shorts, muscle shirts, tattered denims, and slippers are not allowed.</li>
              <li><strong>Women:</strong> Shorts, sleeveless or hanging blouses, sleeveless dresses, tops with low or plunging neckline, miniskirts, tattered denims, and slippers are not allowed.</li>
            </ul>
          </li>
          <li>Wearing of slippers will only be allowed during floods and other major weather disturbances.</li>
          <li>The prescribed hairstyle for male students is short (exposing the nape) and fringe of banged hairs.</li>
          <li>Students not in proper uniform will not be allowed to attend their classes and shall be marked absent.</li>
          <li>Students are not allowed to attend their academic classes in PE or NSTP uniform.</li>
          <li>All students must refrain from having body piercings and excessive use of accessories and loud or heavy hair coloring. Wearing of dangling or very large earrings for female students is prohibited. Such accessories will be immediately confiscated.</li>
        </ul>

        <h3 id="use-of-facilities">B. On the Use of School Facilities</h3>
        <ul>
          <li>Observe library and computer science laboratory rules and regulations.</li>
          <li>Conserve water and energy whenever possible. Turn off lights and faucets when not needed.</li>
          <li>Exert utmost care and concern in handling laboratory equipment.</li>
          <li>Keep the comfort rooms clean. Close the faucets when not in use.</li>
          <li>Help keep the campus clean and orderly. Refrain from acts of vandalism.</li>
        </ul>
      </section>

      <section id="standards" aria-labelledby="standards-heading">
        <h2 id="standards-heading">Standards of Conduct</h2>
        <p>All students are expected to conduct themselves in a manner befitting a student of the College, and not to violate any of the rules and regulations of the College.</p>

        <h3 id="classification">A. Classification of Violations/Offenses</h3>
        <h4 id="light-offenses">Light Offenses</h4>
        <p>Light offenses are punished by fine or warning. Commission of three light offenses aggravates the nature of offense to less grave (moderate) and grave depending on the likelihood of habitual delinquency. The following are considered light offenses:</p>
        <ul>
          <li>Violation of the Policy on ID, school uniform and attire</li>
          <li>Violation of the Policy on the use of school facilities</li>
          <li>Loitering along the hallway during class hours</li>
        </ul>

        <h4 id="less-grave-offenses">Less Grave Offenses (Moderate)</h4>
        <p>Offenses which are not very serious in nature. Suspension from school not to exceed three (3) days may be imposed as a punishment. However, parents must be informed by the Office of the Discipline Services or the Dean of any misconduct on the part of their children for which disciplinary action is necessary.</p>
        <ul>
          <li>Use of curses and vulgar words and roughness in all aspects of behavior.</li>
          <li>Use of cellular phones and other gadgets during classes and/or academic functions. Playing loud music from gadgets inside the classroom or along the corridors during break time.</li>
          <li>Posting of posters, streamers, or banners within school premises without prior permission or approval from the Office of the Student Affairs.</li>
          <li>Public display of intimacy whether inside or outside the College especially while in uniform.</li>
          <li>Deliberate cutting of classes or walking out from classes during class hours.</li>
          <li>Playing loud music from gadgets and performing other disruptive acts during classes.</li>
        </ul>

        <h4 id="grave-offenses">Grave Offenses</h4>
        <p>For a persistent offender or one guilty of a serious offense, a suspension for not more than one (1) year may be imposed. The school, however, should forward to the Commission of Higher Education Regional Office concerned within ten (10) days from dissolution of the investigation of the case for its information.</p>
        <ul>
          <li>Smoking, gambling, or drinking hard drinks while in school uniform even outside the campus</li>
          <li>Vandalism</li>
          <li>Theft and willful destruction of school equipment and properties</li>
          <li>Hooliganism and brawls on campus</li>
          <li>Violation of the Dangerous Drugs Law and other related laws</li>
          <li>Forging, falsifying, and tampering of official school documents and records</li>
          <li>Carrying of firearms, explosives, and deadly weapons such as ice picks or blades which are more than 1 ½ inches long and other similar objects within the school premises</li>
          <li>Use of offensive words and disrespectful deed towards any members of the faculty, administrators, non-teaching personnel and co-students</li>
          <li>Dishonesty and cheating in any forms</li>
          <li>Gross misconduct</li>
          <li>Hazing</li>
          <li>Drunkenness/Drinking liquor or bringing intoxicating beverages while inside the campus</li>
          <li>Assaulting a co-student or school personnel, directly or indirectly, and in relation to the cybercrime law</li>
          <li>Instigating or leading illegal strikes or similar concerted activities resulting in the stoppage of classes</li>
          <li>Preventing or threatening any pupil or student or school personnel from entering the school premises or attending classes or discharging their duties</li>
          <li>Illegal use of school name, seal and logo for solicitation and other unlawful activities</li>
          <li>Any form of cybercrime against co-student, faculty, staff, or the institution</li>
          <li>Performing acts and other offenses putting the name of the College in bad light</li>
          <li>Displaying of obscene and/or sexually-oriented personal photos and videos in the internet</li>
          <li>Entering movie houses, clubs, bars, and the like while in school uniform</li>
          <li>Any form of extortions, blackmailing, and the like among co-students</li>
          <li>Recruitment of students to join in organizations or clubs or organized groups not accredited by the College</li>
          <li>All other unlawful acts</li>
        </ul>
        <p>The College reserves the right to promulgate future rules and regulations for offenses not contemplated in this student manual. In the absence of school rules defining and punishing an unlawful act, the Philippine general laws shall be the basis. Violation of the general laws of the land committed within the campus shall authorize the Committee to impose discipline to erring students.</p>

        <h3 id="procedure">B. Procedure of Processing of Student Discipline Cases</h3>
        <p>In the processing of discipline cases, the College strives to provide for expeditious adjudication of student discipline cases, inculcate a sense of justice among students and develop in them self-discipline, maximize student learning experience by establishing a just and humane penalty or sanction, provide for remedies to redress a wrong and protect the interests of the students.</p>

        <h4 id="csd-composition">Committee on Student Discipline (CSD) – Composition</h4>
        <ul>
          <li>The Discipline Services Coordinator sitting as the Chairman</li>
          <li>Representative from the School Administration</li>
          <li>Representative from the Institute Student Council</li>
          <li>Representative from the Mabalacat College Student Council</li>
          <li>Representative from the members of the Faculty</li>
        </ul>

        <h4 id="jurisdiction">C. Jurisdiction of the Committee on Student Discipline (CSD)</h4>
        <p>The Committee on Student Discipline has the jurisdiction to hear and decide the following cases, without prejudice to the complainant’s right to seek redress of grievance in proper venue:</p>
        <ul>
          <li>Violation of the policies in the Student Manual</li>
          <li>Violation of a School Memorandum</li>
          <li>Crimes involving moral turpitude</li>
          <li>Other unlawful acts</li>
        </ul>

        <h4 id="filing">D. Filing of a Complaint and Reply Thereof</h4>
        <ol>
          <li>A complaint should be in writing, dated, and signed. Oral complaints will not be accepted. The complainant should personally submit the written complaint to the Discipline Services Office in three copies. Additional copies may be required if there is more than one erring student.</li>
          <li>A complaint should state:
            <ul>
              <li>The name of the complainant and the name of the other student/s involved (e.g., the offender/s). When the offense is committed by more than one student, all of them shall be included in the complaint.</li>
              <li>The acts or omissions complained of, the damages caused, and the remedy sought.</li>
              <li>If the offense is specified in the Student Handbook or Philippine laws, its designation should be stated.</li>
              <li>The date of the commission of the offense and the place where it was committed.</li>
            </ul>
          </li>
          <li>The Discipline Services Coordinator shall evaluate the complaint and determine whether the acts or omissions constitute an infraction of the Student Handbook, standing school memoranda, or the laws of the Republic of the Philippines, and whether there are sufficient grounds to hold the erring student for due process.</li>
          <li>If the Discipline Services Coordinator finds the complaint sufficient in form and substance and that there is a strong possibility that the act complained of constitutes an offense, the Coordinator shall convene the Committee on Student Discipline (CSD). The CSD shall order the erring student to reply within 48 hours.</li>
          <li>The erring student should submit the reply to the CSD in three copies. Additional copies shall be required if there is more than one complaint. Failure to submit a reply within the specified time shall be deemed a waiver of the right to file a reply. Requests for extension shall be allowed at the sound discretion of the Committee.</li>
          <li>Upon receipt of the reply, the complainant may, at his discretion, write a comment to the response within forty-eight (48) hours from receipt thereof. Upon receipt of the comment, the erring student may also make a reply to the comment within forty-eight (48) hours from receipt thereof. After the lapse of forty-eight (48) hours without comment or reply filed, the submission of said pleadings shall be deemed waived.</li>
        </ol>

        <h4 id="hearing">E. Hearing</h4>
        <ol>
          <li>After the submission of the last pleading, the parties are notified by the CSD of the date and time of hearing. The parties are requested to bring their witnesses and evidence to support their claims.</li>
          <li>During the hearing, the complainant shall first establish their cause in the presence of the erring student, producing testimonial, documentary, and object evidence. The complainant shall be examined, through questions and answers, either by the CSD or by the erring student to ascertain the veracity of the claims.</li>
          <li>The erring student may, during the same hearing, present testimonial, documentary, and other pieces of evidence in defense of himself/herself, and will likewise be examined by the CSD.</li>
          <li>Unjustified absence of any party during the hearing shall not postpone the hearing. The absent party’s right to present any form of evidence apart from those submitted as part of his/her pleadings shall be waived.</li>
        </ol>

        <h4 id="decision">F. Decision and Range of Penalties/Sanctions</h4>
        <ul>
          <li>If the erring student pleaded “guilty,” the case is immediately decided and the penalty is one step lower.</li>
          <li>After the hearing of a case, the CSD shall release the decision within fifteen (15) days from the last day of hearing. The erring student shall be notified of the decision.</li>
          <li>If the decision is contested, the erring student may submit an appeal to the Vice-President of Student Affairs and Services (VPSAS) within fifteen (15) days from receipt of the decision. If the decision of the VPSAS is still contested, the erring student may submit another appeal letter to the College President within another fifteen (15) days. The decision of the College President is final and executory.</li>
          <li>For non-appealed decisions of the CSD, the recommendations become executory.</li>
        </ul>
        <p>The list of sanctions/penalties includes but is not limited to the following: verbal reprimand, written undertaking, community service, public apology, suspension, exclusion, and expulsion.</p>

